function openGuide() {
  UI.openWindow('guide', 'دليل الاستخدام', { width: 760, height: 520 }, (body, win) => {
    const bar = UI.toolbar([{ key: 'close', label: 'إغلاق', icon: 'close', onClick: () => win.close() }])
    const doc = UI.el(`<div class="guide"><nav>${GUIDE.map(([t], i) => `<a href="#" data-i="${i}">${t}</a>`).join('')}</nav>
      <article>${GUIDE.map(([t, h], i) => `<section id="g-${i}"><h3>${t}</h3>${h}</section>`).join('')}</article></div>`)
    doc.querySelectorAll('nav a').forEach((a) => (a.onclick = (e) => { e.preventDefault(); doc.querySelector(`#g-${a.dataset.i}`).scrollIntoView({ behavior: 'smooth' }) }))
    body.append(bar, doc)
  })
}
